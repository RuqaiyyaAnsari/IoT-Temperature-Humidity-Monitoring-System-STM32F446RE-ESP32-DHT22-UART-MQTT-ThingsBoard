/* Wait until the pin reaches 'level'. Returns 0 on timeout. */
static uint8_t wait_level(uint8_t level, uint16_t timeout_us)
{
    __HAL_TIM_SET_COUNTER(&htim6, 0);
    while (HAL_GPIO_ReadPin(DHT22_GPIO_Port, DHT22_Pin) != level)
    {
        if (__HAL_TIM_GET_COUNTER(&htim6) > timeout_us) return 0;
    }
    return 1;
}

/* Returns 0 = OK, 1-5 = error stage, 6 = checksum error */
uint8_t DHT22_Read(float *temp, float *hum)
{
    uint8_t d[5] = {0};

    /* 1. Start signal: pull low for 2 ms, then release */
    HAL_GPIO_WritePin(DHT22_GPIO_Port, DHT22_Pin, GPIO_PIN_RESET);
    HAL_Delay(2);
    __disable_irq();                       /* timing is critical from here */
    HAL_GPIO_WritePin(DHT22_GPIO_Port, DHT22_Pin, GPIO_PIN_SET);
    delay_us(30);

    /* 2. Sensor response: 80 us low, 80 us high */
    if (!wait_level(0, 100)) { __enable_irq(); return 1; }
    if (!wait_level(1, 100)) { __enable_irq(); return 2; }
    if (!wait_level(0, 100)) { __enable_irq(); return 3; }

    /* 3. Read 40 bits */
    for (int i = 0; i < 40; i++)
    {
        if (!wait_level(1, 100)) { __enable_irq(); return 4; }  /* 50 us low ends */
        delay_us(40);                                            /* sample point   */
        if (HAL_GPIO_ReadPin(DHT22_GPIO_Port, DHT22_Pin))
            d[i / 8] |= (1 << (7 - (i % 8)));                    /* still high = 1 */
        if (!wait_level(0, 100)) { __enable_irq(); return 5; }
    }
    __enable_irq();

    /* 4. Checksum: byte 4 = sum of bytes 0..3 */
    if ((uint8_t)(d[0] + d[1] + d[2] + d[3]) != d[4]) return 6;

    /* 5. Convert */
    *hum = ((d[0] << 8) | d[1]) / 10.0f;
    int16_t t = ((d[2] & 0x7F) << 8) | d[3];
    *temp = t / 10.0f;
    if (d[2] & 0x80) *temp = -*temp;        /* bit 15 = sign */
    return 0;
}
